class OSConstructViolation(BaseModel):
    """A single OS construct violation found in a command."""

    step_id: int = Field(description="Step ID where violation was found")
    command: str = Field(description="The command containing the violation")
    violation: str = Field(description="The specific violation found (e.g., 'powershell.exe')")
    source: str = Field(description="Detection source: 'pattern' or 'llm'")


class EvaluationMeasure(BaseModel):
    """A single pass/fail evaluation measure."""

    name: str = Field(description="Name of the measure")
    passed: bool = Field(description="Whether the measure passed")
    detail: str = Field(default="", description="Details if failed, empty if passed")


class EvaluationMetadata(BaseModel):
    """Metadata for the evaluation process."""

    source_file: str
    control_file: str
    source_os: str
    target_os: str
    evaluated_at: datetime
    model: str


class EvaluationResult(BaseModel):
    """Complete evaluation output with pass/fail measures."""

    metadata: EvaluationMetadata
    missing_steps: EvaluationMeasure = Field(
        description="Are any steps in the control missing from the variant?"
    )
    extra_steps: EvaluationMeasure = Field(
        description="Are any new steps present in the variant not in control?"
    )
    os_constructs_valid: EvaluationMeasure = Field(
        description="Does the procedure avoid Windows-only constructs on non-Windows?"
    )
    technique_ids_match: EvaluationMeasure = Field(
        description="Do variant and control map to the same ATT&CK technique IDs (exact match)?"
    )
    parent_technique_ids_match: EvaluationMeasure = Field(
        description="Do variant and control map to the same parent ATT&CK techniques (ignores subtechnique)?"
    )
    telemetry_classes_match: EvaluationMeasure = Field(
        description="Does variant generate the same telemetry classes as control?"
    )
    extra_telemetry_classes: EvaluationMeasure = Field(
        description="Are additional telemetry classes present in variant?"
    )
    telemetry_diversity: EvaluationMeasure = Field(
        description="Does variant have same level of telemetry diversity as control?"
    )
    telemetry_multi_class: EvaluationMeasure = Field(
        description="Does execution generate telemetry in more than one telemetry class?"
    )
    technique_sequence_match: EvaluationMeasure = Field(
        description="Does variant preserve the same ordered sequence of techniques as control?"
    )
    tactic_sequence_match: EvaluationMeasure = Field(
        description="Does variant preserve the same ordered sequence of tactics as control?"
    )
    privilege_progression_match: EvaluationMeasure = Field(
        description="Does variant preserve the same privilege context progression as control?"
    )
    all_pass: bool = Field(description="True if all measures passed")

    def to_csv_row(self) -> dict:
        """Convert to a flat dictionary for CSV output."""

        def sanitize(text: str) -> str:
            """Remove newlines and CRLF from text for CSV compatibility."""
            return text.replace("\r\n", " ").replace("\n", " ").replace("\r", " ")

        return {
            "source_file": self.metadata.source_file,
            "control_file": self.metadata.control_file,
            "source_os": self.metadata.source_os,
            "target_os": self.metadata.target_os,
            "evaluated_at": self.metadata.evaluated_at.isoformat(),
            "model": self.metadata.model,
            "missing_steps_pass": self.missing_steps.passed,
            "missing_steps_detail": sanitize(self.missing_steps.detail),
            "extra_steps_pass": self.extra_steps.passed,
            "extra_steps_detail": sanitize(self.extra_steps.detail),
            "os_constructs_pass": self.os_constructs_valid.passed,
            "os_constructs_detail": sanitize(self.os_constructs_valid.detail),
            "technique_ids_pass": self.technique_ids_match.passed,
            "technique_ids_detail": sanitize(self.technique_ids_match.detail),
            "parent_technique_ids_pass": self.parent_technique_ids_match.passed,
            "parent_technique_ids_detail": sanitize(self.parent_technique_ids_match.detail),
            "telemetry_classes_pass": self.telemetry_classes_match.passed,
            "telemetry_classes_detail": sanitize(self.telemetry_classes_match.detail),
            "extra_telemetry_pass": self.extra_telemetry_classes.passed,
            "extra_telemetry_detail": sanitize(self.extra_telemetry_classes.detail),
            "telemetry_diversity_pass": self.telemetry_diversity.passed,
            "telemetry_diversity_detail": sanitize(self.telemetry_diversity.detail),
            "telemetry_multi_class_pass": self.telemetry_multi_class.passed,
            "telemetry_multi_class_detail": sanitize(self.telemetry_multi_class.detail),
            "technique_sequence_pass": self.technique_sequence_match.passed,
            "technique_sequence_detail": sanitize(self.technique_sequence_match.detail),
            "tactic_sequence_pass": self.tactic_sequence_match.passed,
            "tactic_sequence_detail": sanitize(self.tactic_sequence_match.detail),
            "privilege_progression_pass": self.privilege_progression_match.passed,
            "privilege_progression_detail": sanitize(self.privilege_progression_match.detail),
            "all_pass": self.all_pass,
        }


class FullPipelineOutput(BaseModel):
    """Complete output from full pipeline with enriched procedure."""

    metadata: ProcedureMetadata
    environment: dict = Field(description="Original and converted host environments")
    procedure: EnrichedTTPOutput = Field(description="Enriched procedure with D3FEND observables")
    intermediate_output: dict = Field(description="Validation and conversion notes")
    evaluation: EvaluationResult | None = Field(
        default=None, description="EvaluationResult if control file provided, else null"
    )
