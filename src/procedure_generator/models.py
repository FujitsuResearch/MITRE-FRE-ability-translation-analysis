"""Pydantic models for procedure transformation pipeline."""

from datetime import datetime
from enum import Enum

from pydantic import BaseModel, Field

# =============================================================================
# Core TTP Models - Base (used by Translate/Validate)
# =============================================================================


class ActionStepBase(BaseModel):
    """Step as output by translate node - no tracking fields."""

    tactic: str = Field(description="MITRE ATT&CK tactic (e.g., 'Initial Access', 'Discovery')")
    technique_id: str = Field(description="MITRE ATT&CK technique ID (e.g., 'T1021.001')")
    technique_name: str = Field(
        description="MITRE ATT&CK technique name (e.g., 'Remote Desktop Protocol')"
    )
    os: str = Field(description="Operating system (Windows, Linux, macOS)")
    command: str = Field(description="The command to execute")
    description: str = Field(description="What this step accomplishes")
    # FRE: Start of new code
    required_privilege: str = Field(
        description="Required privilege level (e.g., 'user', 'elevated')"
    )
    dependencies_constraints: str = Field(
        description="Any dependencies or OS-specific constraints for this step (e.g., 'Requires PowerShell 5.0 or later')"
    )
    telemetry_expected: str = Field(
        description="Expected telemetry generated by this step including telemetry class, platform, sensor requirement, eventID, and any other relevant details "
        "(e.g., 'Process creation event with command line arguments, requires Sysmon with ProcessCreate enabled')"
    )
    # FRE: End of new code


class TTPOutputBase(BaseModel):
    """Output from translate node - flat action sequence."""

    action_sequence: list[ActionStepBase]


# =============================================================================
# Core TTP Models - Full (used by Convert/Refine/Output)
# =============================================================================


class ActionStep(BaseModel):
    """Step with full tracking fields - output by convert node."""

    step_id: int = Field(description="Sequential ID in the action sequence")
    original_step_id: int | None = Field(
        default=None, description="Reference to original step if split (null for 1:1 conversions)"
    )
    tactic: str = Field(description="MITRE ATT&CK tactic")
    technique_id: str = Field(description="MITRE ATT&CK technique ID")
    technique_name: str = Field(description="MITRE ATT&CK technique name")
    os: str = Field(description="Operating system")
    host: str = Field(
        description="Target host where command executes (e.g., 'attacker-kali', '10.20.10.16')"
    )
    command: str = Field(description="The command to execute")
    description: str = Field(description="What this step accomplishes")
    # FRE: Start of new code
    required_privilege: str = Field(
        description="Required privilege level (e.g., 'user', 'elevated')"
    )
    dependencies_constraints: str = Field(
        description="Any dependencies or OS-specific constraints for this step (e.g., 'Requires PowerShell 5.0 or later')"
    )
    telemetry_expected: str = Field(
        description="Expected telemetry generated by this step including telemetry class, platform, sensor requirement, eventID, and any other relevant details "
        "(e.g., 'Process creation event with command line arguments, requires Sysmon with ProcessCreate enabled')"
    )
    # FRE: End of new code


class TTPOutput(BaseModel):
    """Complete output structure with tracking fields."""

    action_sequence: list[ActionStep]


# =============================================================================
# Stage 2: Validation Models
# =============================================================================


class ValidationIssueType(str, Enum):
    MISSING_STEP = "missing_step"
    INCORRECT_TTP = "incorrect_ttp"
    INACCURATE_PURPOSE = "inaccurate_purpose"
    COMMAND_MISMATCH = "command_mismatch"
    MISC = "miscellaneous"


class ValidationIssue(BaseModel):
    """A single validation issue found during verification."""

    issue_type: ValidationIssueType
    location: str = Field(description="JSON path to the issue location")
    original: str | None = Field(default=None, description="Original value (null if missing)")
    corrected: str = Field(description="Corrected value")
    justification: str = Field(description="Reason for the correction")


class ValidationResult(BaseModel):
    """Result of validating a TTPOutputBase."""

    is_valid: bool = Field(description="True if no issues found")
    validated_output: TTPOutputBase = Field(description="Corrected TTPOutputBase structure")
    validation_issues: list[ValidationIssue] = Field(default_factory=list)


# =============================================================================
# Stage 3: OS Conversion Models
# =============================================================================


class ConversionType(str, Enum):
    DIRECT = "direct"  # 1:1 command mapping
    EQUIVALENT = "equivalent"  # Different command, same result
    APPROXIMATION = "approximation"  # Similar but not identical behavior
    UNSUPPORTED = "unsupported"  # No equivalent on target OS


class ConversionNote(BaseModel):
    """Documentation for a single action conversion."""

    original_action: str = Field(description="Source OS command")
    converted_action: str | None = Field(
        default=None, description="Target OS command (null if unsupported)"
    )
    conversion_type: ConversionType
    notes: str = Field(description="Explanation of conversion choices")


class ConversionResult(BaseModel):
    """Result of OS conversion process."""

    converted_output: TTPOutput = Field(description="TTPOutput for target OS")
    conversion_notes: list[ConversionNote] = Field(default_factory=list)


# =============================================================================
# Stage 3.5: Environment Extraction Models
# =============================================================================


class EnvironmentHost(BaseModel):
    """A host in the adversary's execution environment."""

    identifier: str = Field(
        description="Host identifier (hostname, IP, or descriptive name like 'attacker-kali')"
    )
    os: str = Field(description="Operating system (windows, linux, macos)")
    role: str | None = Field(
        default=None, description="Role in the attack (e.g., 'attacker', 'pivot', 'target')"
    )
    # FRE: Start of new code
    privileges: str | None = Field(
        default=None, description="Adversary privileges on the host (e.g., 'user', 'admin', 'root')"
    )
    # FRE: End of new code


class EnvironmentMap(BaseModel):
    """Map of hosts the adversary executes commands on."""

    hosts: list[EnvironmentHost] = Field(
        description="List of execution hosts identified in the procedure"
    )


class ConvertedEnvironment(BaseModel):
    """Result of environment conversion - hosts with updated OS values."""

    converted_hosts: list[EnvironmentHost] = Field(
        description="List of hosts after OS conversion applied"
    )


# =============================================================================
# Stage 4: Refinement Models
# =============================================================================


class RefinementType(str, Enum):
    SYNTAX_FIX = "syntax_fix"
    PATH_CORRECTION = "path_correction"
    PERMISSION_NOTE = "permission_note"
    DEPENDENCY_ADD = "dependency_add"
    COMMAND_UPDATE = "command_update"


class Severity(str, Enum):
    INFO = "info"
    WARNING = "warning"
    ERROR = "error"


class RefinementAction(BaseModel):
    """A single refinement made during validation."""

    action_index: int = Field(description="Index in action_sequence")
    refinement_type: RefinementType
    before: str
    after: str
    reason: str


class ValidationWarning(BaseModel):
    """Warning or issue found during validation."""

    severity: Severity
    message: str


class RefinementResult(BaseModel):
    """Result of conversion validation pass."""

    is_valid: bool
    refined_output: TTPOutput
    refinement_actions: list[RefinementAction] = Field(default_factory=list)
    warnings: list[ValidationWarning] = Field(default_factory=list)


# =============================================================================
# Stage 5: Output Models
# =============================================================================


class ProcedureMetadata(BaseModel):
    """Metadata for the generated procedure."""

    source_file: str
    source_os: str
    target_os: str
    generated_at: datetime
    model: str
    total_duration_ms: int = Field(default=0, description="Total duration in milliseconds")


class ValidationSummary(BaseModel):
    """Summary of validation across all stages."""

    initial_validation_issues: int
    conversion_notes_count: int
    refinements_applied: int
    warnings: list[str] = Field(default_factory=list)


class FinalOutput(BaseModel):
    """Complete output structure for variant test."""

    metadata: ProcedureMetadata
    procedure: TTPOutput
    validation_summary: ValidationSummary


